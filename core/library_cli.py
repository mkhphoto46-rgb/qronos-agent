from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from core.artifact_registry import ArtifactRegistry
from core.artifact_service import ArtifactProducerRegistry, ArtifactProvenance
from core.storage_locations import load_storage_locations


def _payload() -> dict[str, object]:
    raw=sys.stdin.read().strip()
    if not raw: return {}
    parsed=json.loads(raw)
    return parsed if isinstance(parsed,dict) else {}


def _ids(payload: dict[str, object]) -> list[str]:
    raw=payload.get("ids",[])
    if not isinstance(raw,list): return []
    return [str(x).strip() for x in raw if str(x).strip()]


def _pick_folder() -> str:
    try:
        import tkinter as tk
        from tkinter import filedialog
        root=tk.Tk(); root.withdraw(); root.attributes('-topmost',True)
        path=filedialog.askdirectory(title="انتخاب پوشه برای Qronos")
        root.destroy(); return path or ""
    except Exception:
        return ""


def main() -> int:
    if len(sys.argv)<2: raise ValueError("Library operation is required.")
    op=sys.argv[1].strip().lower(); payload=_payload(); registry=ArtifactRegistry()
    producer=ArtifactProducerRegistry(registry)
    if op=="snapshot":
        items=[x.public() for x in registry.list()]
        loc=load_storage_locations(create=True)
        print(json.dumps({"ok":True,"artifacts":items,"locations":loc.to_public_dict()},ensure_ascii=False)); return 0
    if op=="mark_seen": registry.mark_seen(_ids(payload)); result={"ok":True}
    elif op=="open": registry.open(str(payload.get("id",""))); result={"ok":True}
    elif op=="open_folder": registry.open_folder(str(payload.get("id","")) or None); result={"ok":True}
    elif op=="rename": result={"ok":True,"artifact":registry.rename(str(payload.get("id","")),str(payload.get("name",""))).public()}
    elif op=="delete": result={"ok":True,"results":registry.delete(_ids(payload),forever=False)}
    elif op=="delete_forever": result={"ok":True,"results":registry.delete(_ids(payload),forever=True)}
    elif op=="pick_folder": result={"ok":True,"path":_pick_folder()}
    elif op=="copy": result={"ok":True,"results":registry.copy(_ids(payload),str(payload.get("destination","")))}
    elif op=="move": result={"ok":True,"results":registry.move(_ids(payload),str(payload.get("destination","")))}
    elif op=="register_file":
        item=producer.register_file(
            str(payload.get("path","")),
            origin=str(payload.get("origin","Generated by Qronos")),
            provenance=ArtifactProvenance(
                conversation_id=str(payload.get("sourceConversationId","")),
                message_id=str(payload.get("sourceMessageId","")),
                request_id=str(payload.get("sourceRequestId","")),
            ),
            unread=bool(payload.get("unread",True)),
        )
        result={"ok":True,"artifact":item.public()}
    elif op=="register_link":
        item=producer.register_link(
            str(payload.get("url","")),
            name=str(payload.get("name","")),
            origin=str(payload.get("origin","Collected by Qronos")),
            provenance=ArtifactProvenance(
                conversation_id=str(payload.get("sourceConversationId","")),
                message_id=str(payload.get("sourceMessageId","")),
                request_id=str(payload.get("sourceRequestId","")),
            ),
        )
        result={"ok":True,"artifact":item.public()}
    else: raise ValueError(f"Unsupported library operation: {op}")
    print(json.dumps(result,ensure_ascii=False)); return 0


if __name__ == "__main__":
    try: raise SystemExit(main())
    except Exception as exc:
        print(json.dumps({"ok":False,"error":str(exc)},ensure_ascii=False))
        raise SystemExit(1)
