"""Ed25519 signatures (RFC 8032, section 5.1), in pure Python.

Qronos verifies owner-signed local update manifests with this module; it has no
third-party crypto dependency to keep the offline runtime bundle small. The code
follows the RFC's reference algorithm and is checked against the RFC 8032
section 7.1 test vectors. Verification is strict:

* Public keys must be canonical encodings of a point in the prime-order
  subgroup ([L]A is the identity). The identity, the other seven small-order
  (torsion) points and every mixed-order point (a valid key plus a torsion
  component) are refused, when a key is admitted (``check_public_key``) and
  again on every verification. Without this, the identity key with R = identity
  and S = 0 "verifies" any message.
* R must be a canonical encoding and must not be a small-order point.
* The signature scalar S must be below the group order L (no malleable S + L).
* The check is the cofactorless equation [S]B == R + [k]A of RFC 8032.

Signing is provided for owner tooling and test fixtures. It is not constant-time;
sign only on a trusted machine. Qronos itself never signs anything and holds no
private key.
"""

from __future__ import annotations

import hashlib

P = 2**255 - 19
L = 2**252 + 27742317777372353535851937790883648493
_D = -121665 * pow(121666, P - 2, P) % P
_SQRT_M1 = pow(2, (P - 1) // 4, P)

PUBLIC_KEY_BYTES = 32
SIGNATURE_BYTES = 64


class SignatureError(ValueError):
    """A key or signature is malformed (as opposed to merely not verifying)."""


def _sha512_int(data: bytes) -> int:
    return int.from_bytes(hashlib.sha512(data).digest(), "little")


# Points in extended coordinates (X, Y, Z, T), x = X/Z, y = Y/Z, x*y = T/Z.
def _add(p: tuple[int, int, int, int], q: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    a = (p[1] - p[0]) * (q[1] - q[0]) % P
    b = (p[1] + p[0]) * (q[1] + q[0]) % P
    c = 2 * p[3] * q[3] * _D % P
    d = 2 * p[2] * q[2] % P
    e, f, g, h = b - a, d - c, d + c, b + a
    return e * f % P, g * h % P, f * g % P, e * h % P


def _multiply(scalar: int, point: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    result = (0, 1, 1, 0)
    while scalar > 0:
        if scalar & 1:
            result = _add(result, point)
        point = _add(point, point)
        scalar >>= 1
    return result


def _equal(p: tuple[int, int, int, int], q: tuple[int, int, int, int]) -> bool:
    return (p[0] * q[2] - q[0] * p[2]) % P == 0 and (p[1] * q[2] - q[1] * p[2]) % P == 0


def _recover_x(y: int, sign: int) -> int | None:
    if y >= P:
        return None
    x2 = (y * y - 1) * pow(_D * y * y + 1, P - 2, P)
    if x2 == 0:
        return None if sign else 0
    x = pow(x2, (P + 3) // 8, P)
    if (x * x - x2) % P != 0:
        x = x * _SQRT_M1 % P
    if (x * x - x2) % P != 0:
        return None
    if (x & 1) != sign:
        x = P - x
    return x


_G_Y = 4 * pow(5, P - 2, P) % P
_G_X = _recover_x(_G_Y, 0)
BASE = (_G_X, _G_Y, 1, _G_X * _G_Y % P)


_IDENTITY = (0, 1, 1, 0)


def _is_identity(point: tuple[int, int, int, int]) -> bool:
    return _equal(point, _IDENTITY)


def _small_order(point: tuple[int, int, int, int]) -> bool:
    """True for the eight torsion points (orders 1, 2, 4 and 8)."""
    return _is_identity(_multiply(8, point))


def _prime_order(point: tuple[int, int, int, int]) -> bool:
    """True only for points of the prime-order subgroup generated by BASE."""
    return not _is_identity(point) and _is_identity(_multiply(L, point))


def _compress(point: tuple[int, int, int, int]) -> bytes:
    z_inverse = pow(point[2], P - 2, P)
    x = point[0] * z_inverse % P
    y = point[1] * z_inverse % P
    return int.to_bytes(y | ((x & 1) << 255), 32, "little")


def _decompress(data: bytes) -> tuple[int, int, int, int] | None:
    if len(data) != 32:
        return None
    y = int.from_bytes(data, "little")
    sign = y >> 255
    y &= (1 << 255) - 1
    x = _recover_x(y, sign)
    if x is None:
        return None
    return x, y, 1, x * y % P


def _secret_expand(secret: bytes) -> tuple[int, bytes]:
    if len(secret) != 32:
        raise SignatureError("An Ed25519 private key is 32 bytes.")
    digest = hashlib.sha512(secret).digest()
    scalar = int.from_bytes(digest[:32], "little")
    scalar &= (1 << 254) - 8
    scalar |= 1 << 254
    return scalar, digest[32:]


def public_key(secret: bytes) -> bytes:
    scalar, _ = _secret_expand(secret)
    return _compress(_multiply(scalar, BASE))


def sign(secret: bytes, message: bytes) -> bytes:
    """Owner tooling and test fixtures only; Qronos never signs."""
    scalar, prefix = _secret_expand(secret)
    public = _compress(_multiply(scalar, BASE))
    r = _sha512_int(prefix + message) % L
    encoded_r = _compress(_multiply(r, BASE))
    k = _sha512_int(encoded_r + public + message) % L
    s = (r + k * scalar) % L
    return encoded_r + int.to_bytes(s, 32, "little")


def check_public_key(public: bytes) -> tuple[int, int, int, int]:
    """The decoded point of an acceptable public key; raises SignatureError otherwise."""
    if not isinstance(public, (bytes, bytearray)) or len(public) != PUBLIC_KEY_BYTES:
        raise SignatureError("An Ed25519 public key is 32 bytes.")
    point = _decompress(bytes(public))
    if point is None or _compress(point) != bytes(public):
        raise SignatureError("The Ed25519 public key is not a canonical curve point.")
    if not _prime_order(point):
        raise SignatureError("The Ed25519 public key is a weak (small- or mixed-order) point.")
    return point


def verify(public: bytes, message: bytes, signature: bytes) -> bool:
    """True only for a valid, canonical signature by an acceptable public key."""
    point_a = check_public_key(public)
    if len(signature) != SIGNATURE_BYTES:
        return False
    encoded_r = signature[:32]
    point_r = _decompress(encoded_r)
    if point_r is None or _compress(point_r) != encoded_r or _small_order(point_r):
        return False
    s = int.from_bytes(signature[32:], "little")
    if s >= L:
        return False
    k = _sha512_int(encoded_r + public + message) % L
    return _equal(_multiply(s, BASE), _add(point_r, _multiply(k, point_a)))
