def test_cross_volume_move_removes_the_source_only_after_a_verified_copy(
    box: Sandbox, monkeypatch: pytest.MonkeyPatch,
) -> None:
    item = box.artifact("a.md", "A")
    source = Path(item.path_or_url)
    real_rename = executor_module._rename_no_replace

    def rename_across_volumes(src: Path, dst: Path) -> None:
        if Path(src) == source:
            raise OSError(errno.EXDEV, "cross-device link")
        real_rename(src, dst)

    monkeypatch.setattr(executor_module, "_rename_no_replace", rename_across_volumes)
    approval = box.executor.prepare("move", [item.id], destination=str(box.outside))
    result = box.executor.commit(approval["token"], operation="move")

    assert result["complete"] is True
    assert not source.exists()
    assert (box.outside / "a.md").read_text(encoding="utf-8") == "A"
    assert Path(box.registry.get(item.id).path_or_url) == (box.outside / "a.md").resolve()


