def test_artifact_folder_swapped_for_a_junction_is_refused(box: Sandbox) -> None:
    item = box.artifact(content="same bytes")
    folder = Path(item.path_or_url).parent
    victim_dir = box.outside / "Victim"
    victim_dir.mkdir()
    # Identical content: only the path-resolution check can tell them apart.
    (victim_dir / "report.md").write_text("same bytes", encoding="utf-8")
    folder.rename(box.tmp / "moved-away")
    _junction(folder, victim_dir)

    try:
        with pytest.raises(LibraryActionRefused, match="link or junction"):
            box.executor.prepare("delete", [item.id])
    finally:
        os.rmdir(folder) if os.name == "nt" else folder.unlink()

    assert (victim_dir / "report.md").read_text(encoding="utf-8") == "same bytes"
    assert box.bin.items == []


