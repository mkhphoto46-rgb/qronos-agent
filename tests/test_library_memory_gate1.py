from __future__ import annotations

from pathlib import Path

import pytest

from core.artifact_registry import ArtifactRegistry
from core.artifact_service import (
    ArtifactProducerRegistry,
    ArtifactProvenance,
)


def test_central_artifact_registration_preserves_provenance_and_new_state(
    tmp_path: Path,
) -> None:
    registry = ArtifactRegistry(
        tmp_path / "library.sqlite3",
        tmp_path / "Artifacts",
    )
    producer = ArtifactProducerRegistry(registry)

    created_file = tmp_path / "Artifacts" / "Documents" / "report.md"
    created_file.parent.mkdir(parents=True, exist_ok=True)
    created_file.write_text("# Report", encoding="utf-8")

    artifact = producer.register_file(
        created_file,
        origin="Generated by Qronos",
        provenance=ArtifactProvenance(
            conversation_id="conv-1",
            message_id="msg-1",
            request_id="req-1",
        ),
    )

    assert artifact.read_state == "NEW"
    assert artifact.source_conversation_id == "conv-1"
    assert artifact.source_message_id == "msg-1"
    assert artifact.source_request_id == "req-1"

    registry.mark_seen([artifact.id])
    assert registry.get(artifact.id).read_state == "SEEN"


def test_central_artifact_registration_rejects_unknown_origin(tmp_path: Path) -> None:
    registry = ArtifactRegistry(
        tmp_path / "library.sqlite3",
        tmp_path / "Artifacts",
    )
    producer = ArtifactProducerRegistry(registry)

    created_file = tmp_path / "Artifacts" / "Documents" / "report.md"
    created_file.parent.mkdir(parents=True, exist_ok=True)
    created_file.write_text("# Report", encoding="utf-8")

    with pytest.raises(ValueError):
        producer.register_file(
            created_file,
            origin="Arbitrary user file",  # type: ignore[arg-type]
        )


