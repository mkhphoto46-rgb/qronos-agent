def test_memory_desktop_contract_is_real_and_not_background_polled() -> None:
    root = Path(__file__).resolve().parents[1]

    settings = (
        root / "desktop" / "src" / "components" / "SettingsView.tsx"
    ).read_text(encoding="utf-8")
    store = (root / "desktop" / "src" / "memoryStore.ts").read_text(
        encoding="utf-8"
    )
    runtime = (
        root / "desktop" / "src-tauri" / "src" / "runtime" / "mod.rs"
    ).read_text(encoding="utf-8")
    lib = (
        root / "desktop" / "src-tauri" / "src" / "lib.rs"
    ).read_text(encoding="utf-8")

    assert "useMemoryStore" in settings
    assert "MANAGE MEMORY" in settings
    assert "REBUILD INDEX" in settings
    assert 'invoke<T>("memory_command"' in store
    assert "setInterval" not in store
    assert "pub fn memory_command(" in runtime
    assert "runtime::memory_command" in lib

