"""Reports of ONE multimodal search result (M7): the person's explicit query and its dialogue + frame hits.

The source is never a client: ``MediaService.search_multimodal`` keeps a bounded, expiring, server-side SNAPSHOT of
the exact answer it gave (whitelisted fields only, see :func:`snapshot`) and returns its ``resultId``. A report is
composed from that snapshot after a recheck against the CURRENT index (service): an asset now out of scope, refused
by the Files gate, or whose line/frame row is gone or changed is removed and counted, never silently kept. Nothing
is searched again, no model runs and no media file is read; the asset SHA-256 comes from the index.

Every result keeps its labels: both channels (how each matched), the time alignment, the frame text as GENERATED by
the Vision model and unverified (never a fact, OCR or image similarity), the rank note (not a probability), and the
partial/unavailable notes of the search. No file path is part of a snapshot or a report.
"""
from __future__ import annotations

import csv
from datetime import datetime, timezone
import html
import io
import json
from typing import Any

from qronos_media import reports
from qronos_media.reports import ReportUnavailable, _csv_cell, _plain, clock_text

SEARCH_REPORT_SCHEMA = "qronos.media.search-report/1"
SEARCH_REPORT_FORMATS = reports.FORMATS
TITLE_FA = "گزارش نتیجه‌های جست‌وجوی ترکیبی (گفتگو + تصویر)"
MAX_RESULTS = 50
MAX_FRAMES = 4
MAX_TEXT = 600
MAX_REPORT_BYTES = 8 * 1024 * 1024
PREVIEW_RESULTS = 10
_RELATION_FA = {"during": "هم‌زمان با جمله", "before": "پیش از جمله", "after": "پس از جمله"}
_CHANNEL_FA = {"exact": "دقیق", "fuzzy": "تقریبی", "semantic": "هم‌معنا (bge-m3)", "lexical": "هم‌واژه"}
_OUTCOME_FA = {
    "matched": "نتیجهٔ ترکیبی پیدا شد.",
    "same_asset_outside_window": "هر دو شرط در یک ویدیو پیدا شدند، اما نه در فاصلهٔ زمانی خواسته‌شده.",
    "different_assets": "شرط گفتگو و شرط تصویر هر کدام پیدا شدند، اما در ویدیوهای جدا.",
    "only_dialogue": "فقط شرط گفتگو پیدا شد.", "only_visual": "فقط شرط تصویر پیدا شد.",
    "neither": "هیچ‌کدام از دو شرط پیدا نشد.",
}
_PROVENANCE_KEYS = ("kind", "generated", "verified", "visualVersion", "promptVersion", "promptSha256", "frameSha256",
                    "model", "profile")


def _text(value: Any, limit: int = MAX_TEXT) -> str:
    return _plain(value, limit)


def _number(value: Any) -> int | float | None:
    return value if isinstance(value, (int, float)) and not isinstance(value, bool) else None


def _channels(value: Any, allowed: tuple[str, ...]) -> list[str]:
    return [str(c) for c in (value or []) if c in allowed][:3]


def _semantic(channel: Any) -> dict[str, Any]:
    semantic = (channel or {}).get("semantic") or {}
    return {key: semantic.get(key) for key in ("requested", "status", "reason", "minCosine", "matched")
            if key in semantic}


def snapshot(answer: dict[str, Any]) -> dict[str, Any]:
    """The whitelisted, bounded copy of one ``search_multimodal`` answer that a report may later be composed from."""
    block = answer["multimodal"]
    results = []
    for hit in (block.get("results") or [])[:MAX_RESULTS]:
        line = hit.get("dialogue") or {}
        track = line.get("track") or {}
        frames = []
        for frame in (hit.get("frames") or [])[:MAX_FRAMES]:
            provenance = frame.get("provenance") or {}
            frames.append({
                "timeMs": int(frame["timeMs"]), "frameSha256": str(frame["frameSha256"]),
                "caption": _text(frame.get("caption"), 240),
                "visibleText": [_text(t, 120) for t in (frame.get("visibleText") or [])[:8]],
                "observations": [_text(t, 120) for t in (frame.get("observations") or [])[:6]],
                "channels": _channels(frame.get("channels"), ("lexical", "semantic")),
                "similarity": _number(frame.get("similarity")), "lexicalScore": _number(frame.get("lexicalScore")),
                "relation": str(frame.get("relation")), "gapMs": int(frame.get("gapMs") or 0),
                "generated": True, "verified": False,
                "provenance": {key: provenance[key] for key in _PROVENANCE_KEYS if key in provenance}})
        alignment = hit.get("alignment") or {}
        results.append({
            "assetId": str(hit["assetId"]), "title": _text(hit.get("title"), 300) if hit.get("title") else None,
            "startMs": int(hit["startMs"]), "endMs": int(hit["endMs"]),
            "dialogue": {"startMs": int(line["startMs"]), "endMs": int(line["endMs"]), "text": _text(line.get("text")),
                         "unit": str(line.get("unit")), "channels": _channels(line.get("channels"),
                                                                             ("exact", "fuzzy", "semantic")),
                         "similarity": _number(line.get("similarity")), "lexicalScore": _number(line.get("lexicalScore")),
                         "timing": _text(line.get("timing"), 300),
                         "track": {"trackId": str(track.get("trackId")), "source": track.get("source"),
                                   "language": track.get("language")}},
            "frames": frames, "framesInWindow": int(hit.get("framesInWindow") or len(frames)),
            "alignment": {"relation": str(alignment.get("relation")), "gapMs": int(alignment.get("gapMs") or 0),
                          "windowMs": int(alignment.get("windowMs") or 0), "rule": _text(alignment.get("rule"), 200)},
            "matched": {"dialogue": _channels((hit.get("matched") or {}).get("dialogue"), ("exact", "fuzzy", "semantic")),
                        "visual": _channels((hit.get("matched") or {}).get("visual"), ("lexical", "semantic"))}})
    return {"query": dict(answer["query"]), "searchedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "status": block.get("status"), "outcome": block.get("outcome"), "reason": block.get("reason"),
            "stoppedBy": block.get("stoppedBy"), "notes": [str(n) for n in (block.get("notes") or [])][:20],
            "rankNote": block.get("rankNote"), "counts": dict(block.get("counts") or {}),
            "scope": dict(block.get("scope") or {}),
            "channels": {"dialogue": {"lexical": (block.get("dialogueChannel") or {}).get("lexical"),
                                      "semantic": _semantic(block.get("dialogueChannel"))},
                         "visual": {"semantic": _semantic(block.get("visualChannel"))}},
            "absent": dict(block.get("absent") or {}), "results": results,
            "resultsCut": len(block.get("results") or []) > MAX_RESULTS}


def compose(snap: dict[str, Any], kept: list[dict[str, Any]], removed: dict[str, int],
            sha_by_asset: dict[str, str]) -> dict[str, Any]:
    """The report: the snapshot's query and labels, the hits that survived the recheck, and what was removed."""
    results = [dict(hit, assetSha256=sha_by_asset[hit["assetId"]]) for hit in kept]
    limitations = [
        "این گزارش از نتیجهٔ ذخیره‌شدهٔ همین جست‌وجو و پایگاه دادهٔ نمایه ساخته شده است: جست‌وجو دوباره اجرا نشد، هیچ "
        "مدلی اجرا نشد و هیچ فایل رسانه‌ای خوانده یا دوباره هش نشد (SHA-256 هر ویدیو از نمایه است).",
        "هر نتیجه یک جملهٔ نمایه‌شده (زیرنویس یا رونویسی) و دست‌کم یک فریم از همان ویدیو در فاصلهٔ زمانی خواسته‌شده دارد.",
        "توصیف، متن خوانده‌شده و مشاهده‌های فریم‌ها را مدل بینایی ساخته است: تولیدشده و تأییدنشده، نه واقعیت، نه OCR و "
        "نه شباهت تصویر.",
        "تشخیص گوینده، OCR و رمزگذار تصویر ساخته نشده‌اند و در این جست‌وجو به کار نرفته‌اند.",
        "ترتیب نتیجه‌ها بر پایهٔ فاصلهٔ زمانی و ترتیب هر فهرست است؛ احتمال یا اطمینان کالیبره‌شده نیست.",
    ]
    if any((snap["channels"][c]["semantic"] or {}).get("requested") for c in ("dialogue", "visual")):
        limitations.append("هم‌معنایی با bge-m3 فقط شباهت کسینوسی کالیبره‌نشدهٔ متن است (حداقل ۰٫۵)، نه اثبات معنا.")
    if snap["status"] == "partial":
        limitations.append("این جست‌وجو ناقص بود (" + "، ".join(
            str(r) for r in [snap.get("stoppedBy"), *snap["notes"]] if r) + ")؛ ممکن است همهٔ نتیجه‌ها پیدا نشده باشند.")
    if snap.get("resultsCut"):
        limitations.append(f"فقط {MAX_RESULTS} نتیجهٔ نخست در این گزارش آمده است.")
    if any(removed.values()):
        limitations.append(
            f"پیش از ساختن گزارش، محدوده و دسترسی فعلی دوباره بررسی شد: {removed['outOfScope']} نتیجه خارج از محدوده، "
            f"{removed['permission']} نتیجه بدون اجازهٔ خواندن پوشه و {removed['changed']} نتیجه با شواهد تغییرکرده حذف شد.")
    return {"schema": SEARCH_REPORT_SCHEMA, "kind": "search",
            "generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"), "searchedAt": snap["searchedAt"],
            "query": snap["query"], "status": snap["status"], "outcome": snap["outcome"], "reason": snap.get("reason"),
            "stoppedBy": snap.get("stoppedBy"), "notes": snap["notes"], "rankNote": snap.get("rankNote"),
            "channels": snap["channels"], "scope": snap["scope"], "absent": snap["absent"],
            "recheck": {"kept": len(results), **removed}, "results": results, "limitations": limitations}


def preview(report: dict[str, Any]) -> dict[str, Any]:
    """A bounded slice for the desktop panel (the same schema)."""
    out = {key: report[key] for key in ("schema", "kind", "generatedAt", "searchedAt", "query", "status", "outcome",
                                        "notes", "recheck", "limitations")}
    out["results"] = [{"assetId": r["assetId"], "title": r["title"], "startMs": r["startMs"], "endMs": r["endMs"],
                       "dialogue": {"startMs": r["dialogue"]["startMs"], "text": _text(r["dialogue"]["text"], 300),
                                    "channels": r["dialogue"]["channels"]},
                       "frames": [{"timeMs": f["timeMs"], "caption": f["caption"], "relation": f["relation"],
                                   "gapMs": f["gapMs"], "channels": f["channels"], "generated": True, "verified": False}
                                  for f in r["frames"]]}
                      for r in report["results"][:PREVIEW_RESULTS]]
    out["resultsOmitted"] = max(0, len(report["results"]) - PREVIEW_RESULTS)
    return out


# ------------------------------------------------------------------ renderers (the asset reports' own primitives)


def _channels_fa(names: list[str]) -> str:
    return " + ".join(_CHANNEL_FA.get(n, n) for n in names) or "—"


def _relation_fa(frame: dict[str, Any]) -> str:
    if frame["relation"] == "during":
        return _RELATION_FA["during"]
    return f"{round(frame['gapMs'] / 1000, 1)} ثانیه {_RELATION_FA.get(frame['relation'], frame['relation'])}"


def to_csv(report: dict[str, Any]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\r\n")
    writer.writerow(["result", "asset_sha256", "title", "dialogue_start", "dialogue_end", "dialogue_text",
                     "dialogue_channels", "dialogue_source", "frame_time", "frame_relation", "frame_gap_ms",
                     "frame_text_generated_unverified", "frame_channels", "frame_sha256"])
    for index, hit in enumerate(report["results"], 1):
        line = hit["dialogue"]
        for frame in hit["frames"]:
            writer.writerow([_csv_cell(v) for v in (
                index, hit["assetSha256"], hit["title"], clock_text(line["startMs"]), clock_text(line["endMs"]),
                line["text"], "+".join(line["channels"]), line["track"]["source"], clock_text(frame["timeMs"]),
                frame["relation"], frame["gapMs"], frame["caption"], "+".join(frame["channels"]), frame["frameSha256"])])
    return "﻿" + buffer.getvalue()


def to_html(report: dict[str, Any]) -> str:
    e = lambda value: html.escape("" if value is None else str(value), quote=True)  # noqa: E731
    query = report["query"]
    parts = [
        "<!doctype html>", '<html lang="fa" dir="rtl"><head><meta charset="utf-8">',
        '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; style-src \'unsafe-inline\'">',
        f"<title>{e(TITLE_FA)}</title>",
        "<style>body{font-family:Vazirmatn,Tahoma,sans-serif}td,th{border:1px solid #ccc;padding:4px}"
        "table{border-collapse:collapse}.ltr{direction:ltr;unicode-bidi:embed}</style></head><body>",
        f"<h1>{e(TITLE_FA)}</h1>",
        f"<p>گفتگو: <span dir=\"auto\">{e(query['dialogue'])}</span> ({e(_CHANNEL_FA.get(query['dialogueMatch']))})"
        f" — تصویر: <span dir=\"auto\">{e(query['visual'])}</span> ({e(_CHANNEL_FA.get(query['visualMatch']))})"
        f" — فاصلهٔ زمانی: <span class=\"ltr\">{e(query['windowMs'] // 1000)}</span> ثانیه</p>",
        f"<p>زمان جست‌وجو: <span class=\"ltr\">{e(report['searchedAt'])}</span> — زمان گزارش: "
        f"<span class=\"ltr\">{e(report['generatedAt'])}</span> — طرح: <span class=\"ltr\">{e(report['schema'])}</span></p>",
        f"<p>وضعیت جست‌وجو: {e(report['status'])} — {e(_OUTCOME_FA.get(str(report['outcome']), report['outcome']))}</p>",
        f"<h2>نتیجه‌ها ({len(report['results'])})</h2><table><tr><th>#</th><th>ویدیو</th><th>گفتگو</th>"
        "<th>فریم‌ها (توصیف تولیدشده، تأییدنشده)</th></tr>",
    ]
    for index, hit in enumerate(report["results"], 1):
        line = hit["dialogue"]
        frames = "<br>".join(
            f"<span class=\"ltr\">{e(clock_text(f['timeMs']))}</span> ({e(_relation_fa(f))}؛ {e(_channels_fa(f['channels']))})"
            f" <span dir=\"auto\">{e(f['caption'])}</span> <small class=\"ltr\">{e(f['frameSha256'][:12])}</small>"
            for f in hit["frames"])
        parts.append(f"<tr><td>{index}</td><td dir=\"auto\">{e(hit['title'] or 'ویدیو')}<br>"
                     f"<small class=\"ltr\">{e(hit['assetSha256'][:16])}</small></td>"
                     f"<td><span class=\"ltr\">{e(clock_text(line['startMs']))} – {e(clock_text(line['endMs']))}</span> "
                     f"({e(_channels_fa(line['channels']))}) <span dir=\"auto\">{e(line['text'])}</span></td>"
                     f"<td>{frames}</td></tr>")
    parts.append("</table><h2>محدودیت‌ها</h2><ul>")
    parts += [f"<li>{e(text)}</li>" for text in report["limitations"]]
    parts.append("</ul></body></html>")
    return "\n".join(parts)


def to_pdf(report: dict[str, Any]) -> bytes:
    doc = reports._Pdf(report, title=TITLE_FA, subject=report["searchedAt"])
    width = doc.width
    query = report["query"]
    doc.heading(TITLE_FA, 15)
    doc.pairs([("گفتگو", f"{query['dialogue']} ({_CHANNEL_FA.get(query['dialogueMatch'])})", "auto"),
               ("تصویر", f"{query['visual']} ({_CHANNEL_FA.get(query['visualMatch'])})", "auto"),
               ("فاصلهٔ زمانی (ثانیه)", query["windowMs"] // 1000, "ltr"),
               ("وضعیت جست‌وجو", f"{report['status']} — {_OUTCOME_FA.get(str(report['outcome']), report['outcome'])}", "rtl"),
               ("زمان جست‌وجو", report["searchedAt"], "ltr"), ("زمان گزارش", report["generatedAt"], "ltr"),
               ("طرح گزارش", report["schema"], "ltr")])
    doc.heading(f"نتیجه‌ها ({len(report['results'])})")
    doc.row([("#", 8, "rtl"), ("گفتگو", (width - 8) / 2, "rtl"),
             ("فریم‌ها (توصیف تولیدشده با مدل بینایی، تأییدنشده)", (width - 8) / 2, "rtl")], bold=True)
    for index, hit in enumerate(report["results"], 1):
        line = hit["dialogue"]
        said = (f"{_plain(hit['title'] or 'ویدیو', 80)} — {clock_text(line['startMs'])}–{clock_text(line['endMs'])} "
                f"({_channels_fa(line['channels'])}): {_plain(line['text'], 400)}")
        shown = " / ".join(f"{clock_text(f['timeMs'])} ({_relation_fa(f)}؛ {_channels_fa(f['channels'])}): "
                           f"{_plain(f['caption'], 200)}" for f in hit["frames"])
        doc.row([(str(index), 8, "ltr"), (said, (width - 8) / 2, "auto"), (shown, (width - 8) / 2, "auto")])
    doc.heading("محدودیت‌ها")
    for text in report["limitations"]:
        doc.paragraph("• " + text)
    return doc.output()


def render_bytes(report: dict[str, Any], fmt: str) -> bytes:
    if fmt == "json":
        content = json.dumps(report, ensure_ascii=False, indent=2).encode("utf-8")
    elif fmt == "csv":
        content = to_csv(report).encode("utf-8")
    elif fmt == "html":
        content = to_html(report).encode("utf-8")
    elif fmt == "pdf":
        content = to_pdf(report)
    else:
        raise ValueError(f"format must be one of {SEARCH_REPORT_FORMATS}")
    if len(content) > MAX_REPORT_BYTES:
        raise ReportUnavailable("the search report is larger than its byte budget")
    return content
