export type MediaClient = {
  request(op: MediaOp, fields?: Record<string, unknown>): Promise<MediaResult>;
  /** The person's yes for one approval this client was shown; the secret goes to this one send only. */
  decide(approval: MediaApproval, secret?: string): Promise<MediaResult>;
  decline(approval: MediaApproval): Promise<MediaResult>;
  /** Answers still pending are dropped (resolved as `stale`); late answers are ignored. */
  reset(): void;
  onProgress(listener: (payload: Record<string, unknown>) => void): () => void;
  pending(): number;
  dispose(): void;
};

type Waiter = { resolve: (result: MediaResult) => void; timer: unknown; generation: number; op: MediaOp };

export function createMediaClient(transport: MediaTransport, options: { timeoutMs?: number } = {}): MediaClient {
  const timeoutMs = options.timeoutMs ?? DEFAULT_TIMEOUT_MS;
  const waiters = new Map<string, Waiter>();
  const progress = new Set<(payload: Record<string, unknown>) => void>();
  let generation = 0;
  let counter = 0;
  let unlisten: (() => void) | null = null;
  let listening: Promise<void> | null = null;

  function handle(event: RuntimeEvent): void {
    const parsed = parseMediaEvent(event);
    if (parsed === null) return;
    if (parsed.kind === "progress") {
      progress.forEach((listener) => listener(parsed.payload));
      return;
    }
    const result = parsed.payload as MediaResult;
    const waiter = waiters.get(result.requestId);
    if (!waiter || waiter.generation !== generation || waiter.op !== result.op) return; // late, stale or foreign
    waiters.delete(result.requestId);
    transport.clearTimer(waiter.timer);
    waiter.resolve(result);
  }

  function ensureListening(): Promise<void> {
    if (unlisten) return Promise.resolve();
    if (!listening) {
      listening = transport.listen(handle).then((cleanup) => {
        unlisten = cleanup;
      });
    }
    return listening;
  }

  function nextId(): string {
    counter = (counter + 1) % 1_000_000_000;
    return `m${generation.toString(36)}x${counter.toString(36)}`;
  }

  async function send(op: MediaOp, fields: Record<string, unknown>): Promise<MediaResult> {
    if (!MEDIA_OPS.has(op)) throw new Error(`unknown media operation ${String(op)}`);
    await ensureListening();
    const requestId = nextId();
    const mine = generation;
    const answer = new Promise<MediaResult>((resolve) => {
      const timer = transport.setTimer(() => {
        if (waiters.get(requestId)) {
          waiters.delete(requestId);
          resolve({ requestId, op, ok: false, code: "timeout" });
        }
      }, timeoutMs);
      waiters.set(requestId, { resolve, timer, generation: mine, op });
    });
    try {
      await transport.send(MEDIA_ACTION_ID, { ...fields, op, requestId });
    } catch {
      const waiter = waiters.get(requestId);
      if (waiter) {
        waiters.delete(requestId);
        transport.clearTimer(waiter.timer);
        waiter.resolve({ requestId, op, ok: false, code: "closed" });
      }
    }
    return answer;
  }

  return {
    request(op, fields = {}) {
      if (op === "decide" || op === "decline") throw new Error("use decide/decline for approvals");
      return send(op, fields);
    },
    decide(approval, secret) {
      const fields: Record<string, unknown> = { approvalId: approval.approvalId, approved: true };
      if (approval.needsSecret && typeof secret === "string" && secret.length > 0) fields.secret = secret;
      return send("decide", fields);
    },
    decline(approval) {
      return send("decline", { approvalId: approval.approvalId });
    },
    reset() {
      generation += 1;
      for (const [requestId, waiter] of waiters) {
        transport.clearTimer(waiter.timer);
        waiter.resolve({ requestId, op: waiter.op, ok: false, code: "stale" });
      }
      waiters.clear();
    },
    onProgress(listener) {
      progress.add(listener);
      void ensureListening();
      return () => progress.delete(listener);
    },
    pending() {
      return waiters.size;
    },
    dispose() {
      this.reset();
      progress.clear();
      if (unlisten) unlisten();
      unlisten = null;
    },
  };
}
