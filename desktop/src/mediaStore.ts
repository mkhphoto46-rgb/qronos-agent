/**
 * The media library as the desktop sees it (round 32).
 *
 * Every operation is one typed `qronos.media` runtime action `{op, requestId, ...}` sent through the
 * registered `send_runtime_action` command; the bridge answers with a `media_result` runtime event carrying
 * the same requestId (and `media_progress` events while indexing). Nothing here decides permission,
 * picks a model or touches a file: the runtime's one media host does, behind the Qronos gate.
 *
 * - Only allow-listed operations and bounded fields are sent.
 * - An answer is matched by requestId; an answer nobody is waiting for (late, stale, from a reset panel,
 *   or for another window) is ignored. A request with no answer in time resolves as `timeout`.
 * - A typed approval secret is passed straight to the one `decide` send and never stored here.
 *
 * No runtime imports: the transport (send/listen/timers) is injected, so this module runs in tests as is.
 */

export type MediaOp =
  | "status" | "capabilities" | "roots.list" | "roots.add" | "roots.remove" | "scan" | "index.start"
  | "index.stop" | "index.pause" | "index.resume" | "job.retry" | "job.reindex" | "job.cancel" | "job.pause"
  | "job.resume" | "asset.priority" | "asset.detail" | "search" | "open.prepare" | "report.preview"
  | "report.generate" | "report.export" | "decide" | "decline";

export const MEDIA_OPS: ReadonlySet<string> = new Set<MediaOp>([
  "status", "capabilities", "roots.list", "roots.add", "roots.remove", "scan", "index.start", "index.stop",
  "index.pause", "index.resume", "job.retry", "job.reindex", "job.cancel", "job.pause", "job.resume",
  "asset.priority", "asset.detail", "search", "open.prepare", "report.preview", "report.generate", "report.export",
  "decide", "decline",
]);

/** One topic hit (qronos_media/topics.py): an indexed dialogue segment, its actual lines and why it ranked. */
export type TopicHit = {
  assetId: string;
  title: string | null;
  startMs: number;
  endMs: number;
  source: string;
  language: string | null;
  score: number;
  components: { segment: number; evidence: number; terms: number; expansion: number };
  evidence: Array<{ startMs: number; endMs: number; text: string }>;
  /** A label/summary generated by the Fast brain from the cited lines: model text, unverified (never a quotation). */
  generated: { label: string; summary: string; cites: Array<{ lineId: string; startMs: number }> } | null;
};

export type TopicBlock = {
  hits: TopicHit[];
  note: string | null;
  hints: string[];
  expanded: boolean;
  /** Generated search phrases from the Fast brain (only when asked and the first pass was weak): hints, not facts. */
  brainHints: string[];
  brainHintsReason: string | null;
};

function generatedOf(value: unknown): TopicHit["generated"] {
  if (typeof value !== "object" || value === null) return null;
  const made = value as Record<string, unknown>;
  if (typeof made.label !== "string" || typeof made.summary !== "string" || !Array.isArray(made.cites)) return null;
  const cites = made.cites.filter((cite): cite is Record<string, unknown> => typeof cite === "object" && cite !== null
    && typeof (cite as Record<string, unknown>).lineId === "string" && typeof (cite as Record<string, unknown>).startMs === "number")
    .slice(0, 6).map((cite) => ({ lineId: String(cite.lineId), startMs: cite.startMs as number }));
  if (cites.length === 0) return null; // a generated label is only shown with the indexed lines it cites
  return { label: made.label.slice(0, 60), summary: made.summary.slice(0, 280), cites };
}

function finite(value: unknown): number {
  return typeof value === "number" && Number.isFinite(value) ? value : 0;
}

/** The topic block of a `search` answer in mode "topic", validated field by field; a hit without lines is dropped. */
export function topicBlockOf(result: MediaResult | null): TopicBlock {
  const empty: TopicBlock = { hits: [], note: null, hints: [], expanded: false, brainHints: [], brainHintsReason: null };
  if (!result || !result.ok || typeof result.topic !== "object" || result.topic === null) return empty;
  const block = result.topic as Record<string, unknown>;
  const hits: TopicHit[] = [];
  for (const raw of Array.isArray(block.results) ? block.results.slice(0, 50) : []) {
    if (typeof raw !== "object" || raw === null) continue;
    const item = raw as Record<string, unknown>;
    if (!isAssetId(item.assetId) || typeof item.startMs !== "number" || typeof item.endMs !== "number") continue;
    const evidence = (Array.isArray(item.evidence) ? item.evidence : []).slice(0, 4)
      .filter((line): line is Record<string, unknown> => typeof line === "object" && line !== null
        && typeof (line as Record<string, unknown>).text === "string" && typeof (line as Record<string, unknown>).startMs === "number")
      .map((line) => ({ startMs: line.startMs as number, endMs: finite(line.endMs), text: String(line.text).slice(0, 600) }));
    if (evidence.length === 0) continue; // never a hit without indexed lines
    const parts = (typeof item.components === "object" && item.components !== null ? item.components : {}) as Record<string, unknown>;
    hits.push({
      assetId: item.assetId, title: typeof item.title === "string" ? item.title.slice(0, 300) : null,
      startMs: item.startMs, endMs: item.endMs, source: typeof item.source === "string" ? item.source : "",
      language: typeof item.language === "string" ? item.language : null, score: finite(item.score),
      components: { segment: finite(parts.segment), evidence: finite(parts.evidence), terms: finite(parts.terms),
                    expansion: finite(parts.expansion) },
      evidence,
      generated: generatedOf(item.generated),
    });
  }
  const expansion = (typeof block.expansion === "object" && block.expansion !== null ? block.expansion : {}) as Record<string, unknown>;
  const hints = Array.isArray(expansion.hints)
    ? expansion.hints.filter((word): word is string => typeof word === "string").map((word) => word.slice(0, 40)).slice(0, 6)
    : [];
  const note = block.status === "unavailable"
    ? `جست‌وجوی موضوعی در دسترس نیست: ${refusalText(typeof block.reason === "string" ? block.reason : "model_unavailable")}`
    : null;
  const brain = (typeof block.brainHints === "object" && block.brainHints !== null ? block.brainHints : {}) as Record<string, unknown>;
  const brainHints = brain.applied === true && Array.isArray(brain.hints)
    ? brain.hints.filter((word): word is string => typeof word === "string").map((word) => word.slice(0, 60)).slice(0, 5)
    : [];
  const brainHintsReason = brain.requested === true && brain.applied !== true && typeof brain.reason === "string"
    ? brain.reason.slice(0, 60) : null;
  return { hits, note, hints, expanded: expansion.applied === true, brainHints, brainHintsReason };
}

/** Report formats and kinds the media host renders from the one index schema (qronos_media/reports.py). */
export const REPORT_FORMATS = ["pdf", "html", "json", "csv"] as const;
export const REPORT_KINDS = ["short", "full", "transcript", "evidence"] as const;
export type ReportFormat = (typeof REPORT_FORMATS)[number];
export type ReportKind = (typeof REPORT_KINDS)[number];

export const REPORT_KIND_TEXT: Record<ReportKind, string> = {
  short: "گزارش کوتاه",
  full: "گزارش کامل",
  transcript: "متن گفتار",
  evidence: "گزارش شواهد",
};

/** An export destination must name its format by extension (the host refuses anything else). */
export function exportDestinationProblem(destination: string, format: ReportFormat): string | null {
  const path = destination.trim();
  if (!path) return "مسیر فایل خروجی را بنویسید.";
  if (!path.toLowerCase().endsWith(`.${format}`)) return `مسیر خروجی باید با .${format} تمام شود.`;
  return null;
}

export const MEDIA_ACTION_ID = "qronos.media";
export const MAX_EVENT_CHARS = 2_000_000;
export const DEFAULT_TIMEOUT_MS = 60_000;

export type MediaResult = {
  requestId: string;
  op: MediaOp;
  ok: boolean;
  code?: string;
  [field: string]: unknown;
};

export type MediaApproval = {
  approvalId: string;
  needsSecret: boolean;
  preview: Record<string, unknown>;
  op: MediaOp;
};

export type RuntimeEvent = { eventType: string; status: string; message: string };

export type MediaTransport = {
  send(actionId: string, data: Record<string, unknown>): Promise<void>;
  listen(handler: (event: RuntimeEvent) => void): Promise<() => void>;
  setTimer(callback: () => void, ms: number): unknown;
  clearTimer(handle: unknown): void;
};

const REQUEST_ID = /^[A-Za-z0-9_-]{1,64}$/;
const APPROVAL_ID = /^[A-Za-z0-9_-]{8,128}$/;
const ASSET_ID = /^a_[0-9a-f]{32}$/;

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** A runtime event's media payload, or null when it is not a well-formed media answer. */
export function parseMediaEvent(event: unknown): { kind: "result" | "progress"; payload: Record<string, unknown> } | null {
  if (!isRecord(event) || typeof event.eventType !== "string" || typeof event.message !== "string") return null;
  const kind = event.eventType === "media_result" ? "result" : event.eventType === "media_progress" ? "progress" : null;
  if (kind === null || event.message.length > MAX_EVENT_CHARS) return null;
  let payload: unknown;
  try {
    payload = JSON.parse(event.message);
  } catch {
    return null;
  }
  if (!isRecord(payload)) return null;
  if (kind === "result") {
    if (typeof payload.requestId !== "string" || !REQUEST_ID.test(payload.requestId)) return null;
    if (typeof payload.op !== "string" || !MEDIA_OPS.has(payload.op) || typeof payload.ok !== "boolean") return null;
  }
  return { kind, payload };
}

/** The approval a result asks for, validated; null when it asks for none. */
export function approvalOf(result: MediaResult): MediaApproval | null {
  if (result.status !== "approval_required") return null;
  if (typeof result.approvalId !== "string" || !APPROVAL_ID.test(result.approvalId)) return null;
  return {
    approvalId: result.approvalId,
    needsSecret: result.needsSecret === true,
    preview: isRecord(result.preview) ? result.preview : {},
    op: result.op,
  };
}

export function isAssetId(value: unknown): value is string {
  return typeof value === "string" && ASSET_ID.test(value);
}

